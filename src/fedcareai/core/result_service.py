from pathlib import Path
import json
from typing import Any

from fedcareai.core.api_client import FedCareApiClient
from fedcareai.core.task_service import get_task_dir
from fedcareai.security.privacy import scrub_result_payload
from fedcareai.security.signing import sign_payload
from fedcareai.utils.hashing import sha256_file


class ResultServiceError(Exception):
    pass


def get_result_path(task_id: str, result_type: str | None = None) -> Path:
    """
    Return the local result file path for a task.

    If result_type is not specified, prefer validation result first,
    then aggregation result.
    """
    task_dir = get_task_dir(task_id)

    if result_type == "external_validation":
        return task_dir / "result.json"

    if result_type == "federated_aggregation_update":
        return task_dir / "aggregation_result.json"

    validation_path = task_dir / "result.json"
    aggregation_path = task_dir / "aggregation_result.json"

    if validation_path.exists():
        return validation_path

    if aggregation_path.exists():
        return aggregation_path

    return validation_path


def load_local_result(task_id: str, result_type: str | None = None) -> dict[str, Any]:
    """
    Load a local result file generated by validation or aggregation.
    """
    result_path = get_result_path(task_id, result_type=result_type)

    if not result_path.exists():
        raise FileNotFoundError(
            f"No local result found for task {task_id}. "
            "Run validation or aggregation first."
        )

    return json.loads(result_path.read_text(encoding="utf-8"))


def preview_submission(task_id: str, result_type: str | None = None) -> dict[str, Any]:
    """
    Return a scrubbed version of what would be submitted.
    """
    result = load_local_result(task_id, result_type=result_type)
    return scrub_result_payload(result)


def submit_result(
    task_id: str,
    result_type: str | None = None,
    signing_secret: str | None = None,
) -> dict:
    """
    Submit a locally generated result to the API.

    For external validation:
      submits metrics JSON.

    For aggregation:
      submits metrics/metadata JSON, and if an artifact_path exists,
      uploads the artifact as a separate file.
    """
    client = FedCareApiClient()

    result = load_local_result(task_id, result_type=result_type)
    result = scrub_result_payload(result)

    artifact_path_value = result.pop("artifact_path", None)

    if signing_secret:
        result["signature"] = sign_payload(result, signing_secret)

    if artifact_path_value:
        artifact_path = Path(artifact_path_value)

        if not artifact_path.exists():
            raise FileNotFoundError(f"Artifact file not found: {artifact_path}")

        if "artifact_sha256" not in result:
            result["artifact_sha256"] = sha256_file(artifact_path)

        return client.post_file(
            path=f"/tasks/{task_id}/results",
            file_path=artifact_path,
            field_name="artifact",
            data={"result": json.dumps(result)},
        )

    return client.post(
        path=f"/tasks/{task_id}/results",
        json=result,
    )


def save_result(task_id: str, result: dict[str, Any], filename: str = "result.json") -> Path:
    """
    Save a local result file.
    """
    task_dir = get_task_dir(task_id)
    task_dir.mkdir(parents=True, exist_ok=True)

    result_path = task_dir / filename
    result_path.write_text(json.dumps(result, indent=2), encoding="utf-8")

    return result_path
